"""Embeds the pre-rendered glyph files in the settings page's preview.

Run after tools/gen_aafonts.py:  python3 tools/gen_preview_fonts.py
"""
import base64
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
fonts = sorted((ROOT / 'resources' / 'aafonts').glob('*.bin'))
lines = ['// Generated by tools/gen_preview_fonts.py from resources/aafonts/*.bin; do not edit.',
         'module.exports = {']
for i, f in enumerate(fonts):
    comma = ',' if i < len(fonts) - 1 else ''
    lines.append("  {}: '{}'{}".format(f.stem, base64.b64encode(f.read_bytes()).decode(), comma))
lines.append('};')
(ROOT / 'src' / 'pkjs' / 'preview-fonts.js').write_text('\n'.join(lines) + '\n')
print('wrote', len(fonts), 'fonts')
